#!/usr/bin/env python3
"""Thesis figure: cost of one call on IncludeOS and Linux, under KVM and TCG.

usage: plot.py RESULTS_JSON > syscall-latency-plot.tex
RESULTS_JSON is ../results/testctrl.json (30 runs per system).
Writes a pgfplots bar chart: mean per run, error bars one standard deviation.
"""
import json
import statistics as st
import sys

d = json.load(open(sys.argv[1]))

# (json key, x label); same order as the old matplotlib plot
BENCH = [
    ("gettid_syscall",       r"\texttt{gettid}\\syscall"),
    ("getpid_syscall",       r"\texttt{getpid}\\syscall"),
    ("getpid_libc",          r"\texttt{getpid}\\libc"),
    ("mmap_syscall(256KiB)", r"\texttt{mmap}\\256\,KiB\\syscall"),
    ("mmap_libc(256KiB)",    r"\texttt{mmap}\\256\,KiB\\libc"),
    ("mmap_syscall(1B)",     r"\texttt{mmap}\\1\,B\\syscall"),
    ("mmap_libc(1B)",        r"\texttt{mmap}\\1\,B\\libc"),
    ("malloc(256KiB)",       r"\texttt{malloc}\\256\,KiB"),
    ("malloc(0)",            r"\texttt{malloc}\\0\,B"),
]
# KVM first: those are the ones to compare. Same column order as the tables.
SERIES = [
    ("linux.kvm",     "fill=syslinux, draw=syslinux!60!black",               "Linux, KVM"),
    ("includeos.kvm", "fill=systhis, draw=systhis!60!black",                 "IncludeOS, KVM"),
    ("linux.tcg",     "fill=syslinux!25, draw=syslinux!70!black, postaction={pattern=north east lines, pattern color=syslinux!70!black}", "Linux, emulated"),
    ("includeos.tcg", "fill=systhis!25, draw=systhis!70!black, postaction={pattern=north east lines, pattern color=systhis!70!black}",  "IncludeOS, emulated"),
]

out = []
w = out.append
w("% Generated by fig/syscall-latency.py from repos/syscall-latency/testctrl.json.")
w(r"\begin{tikzpicture}")
w(r"\begin{axis}[")
w(r"  width=\textwidth, height=6.2cm,")
w(r"  ybar=0pt, bar width=6.5pt,")
w(r"  ymode=log, log origin=infty, ymin=30, ymax=2e5,")
w(r"  ylabel={RDTSC cycles (log)}, ylabel style={font=\scriptsize},")
w(r"  y tick label style={font=\scriptsize},")
w(r"  xtick={0,...,%d}, xticklabels={%s}," % (
    len(BENCH) - 1, ",".join("{%s}" % lbl for _, lbl in BENCH)))
w(r"  x tick label style={font=\scriptsize, align=center, text width=1.3cm},")
w(r"  xmin=-0.6, xmax=%.1f, enlarge x limits=false," % (len(BENCH) - 0.4))
w(r"  ymajorgrids, grid style={gray!20, thin},")
w(r"  axis line style={gray!60}, tick style={gray!60}, xtick style={draw=none},")
w(r"  error bars/y dir=both, error bars/y explicit,")
w(r"  error bars/error bar style={black!70, thin},")
w(r"  error bars/error mark options={rotate=90, mark size=1.2pt, black!70},")
w(r"  legend columns=4, legend style={font=\scriptsize, draw=none, fill=none,")
w(r"    at={(0.5,1.02)}, anchor=south, /tikz/every even column/.append style={column sep=8pt}},")
w(r"  legend image code/.code={\draw[#1] (0cm,-0.1cm) rectangle (0.3cm,0.1cm);},")
w(r"]")
for key, style, label in SERIES:
    runs = d[key]
    w(r"\addplot[%s] coordinates {" % style)
    for i, (b, _) in enumerate(BENCH):
        xs = [r[b] for r in runs]
        w("  (%d,%.1f) +- (0,%.1f)" % (i, st.mean(xs), st.stdev(xs)))
    w("};")
w(r"\legend{%s}" % ",".join("{%s}" % lbl for _, _, lbl in SERIES))
w(r"\end{axis}")
w(r"\end{tikzpicture}")
print("\n".join(out))
